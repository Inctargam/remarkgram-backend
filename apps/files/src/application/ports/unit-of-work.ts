/**
 * Непрозрачный для application-слоя контекст текущей транзакции.
 *
 * Application-слой не должен зависеть от Prisma, поэтому здесь используется
 * `unknown`, а не `Prisma.TransactionClient`. Конкретная реализация Unit of Work
 * передаёт внутрь callback настоящий клиент транзакции, а инфраструктурные
 * репозитории приводят этот контекст к типу своего persistence-клиента.
 *
 * Один и тот же `ctx` необходимо передавать во все вызовы репозиториев, которые
 * должны выполниться атомарно в рамках одной транзакции.
 */
export type TransactionContext = unknown;

/** Настройки запуска транзакции. */
export type TransactionOptions = {
  /**
   * Максимальное время в миллисекундах, в течение которого реализация ожидает
   * возможность начать транзакцию (например, получить соединение из пула).
   */
  maxWait?: number;

  /**
   * Максимальная продолжительность транзакции в миллисекундах. После превышения
   * лимита реализация должна прервать транзакцию и откатить её изменения.
   */
  timeout?: number;
};

/**
 * Порт для атомарного выполнения нескольких операций с хранилищем.
 *
 * Пример использования:
 *
 * ```ts
 * await unitOfWork.run(async (ctx) => {
 *   const deletedPost = await postsRepository.softDelete(params, ctx);
 *   const event = PostDeletedV1Factory.create(deletedPost);
 *   await outboxEventsRepository.add(event, ctx);
 * });
 * ```
 *
 * Если callback завершился успешно, реализация фиксирует транзакцию. Если он
 * выбросил ошибку, реализация откатывает все выполненные внутри него изменения.
 * Не следует сохранять `ctx` и использовать его после завершения callback.
 */
export abstract class UnitOfWork {
  /**
   * Запускает `handler` внутри одной транзакции и возвращает его результат.
   *
   * @typeParam T Тип значения, которое возвращает callback после успешной
   * транзакции. Для команд без результата обычно используется `void`.
   * @param handler Операция, получающая контекст текущей транзакции.
   * @param options Необязательные ограничения ожидания и выполнения транзакции.
   */
  abstract run<T>(handler: (ctx: TransactionContext) => Promise<T>, options?: TransactionOptions): Promise<T>;
}
